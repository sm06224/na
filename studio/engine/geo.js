// 2 点間の距離（km）。BCP 露出の判定に使う。
export const geoKm = (a, b) => {
  const R = 6371, d2r = Math.PI / 180;
  const dLat = (b[0] - a[0]) * d2r, dLng = (b[1] - a[1]) * d2r;
  const s = Math.sin(dLat / 2) ** 2 + Math.cos(a[0] * d2r) * Math.cos(b[0] * d2r) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
};

export const geoInPoly = (p, poly) => {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const yi = poly[i][0], xi = poly[i][1], yj = poly[j][0], xj = poly[j][1];
    if ((yi > p[0]) !== (yj > p[0]) && p[1] < ((xj - xi) * (p[0] - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};

const geoLineKm = (p, pts) => {                              // 点→折れ線の最短距離（km・概算）
  let best = Infinity;
  for (let i = 0; i + 1 < pts.length; i++) {
    const a = pts[i], b = pts[i + 1];
    const t = Math.max(0, Math.min(1,
      ((p[0] - a[0]) * (b[0] - a[0]) + (p[1] - a[1]) * (b[1] - a[1]))
      / (((b[0] - a[0]) ** 2 + (b[1] - a[1]) ** 2) || 1)));
    best = Math.min(best, geoKm(p, [a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])]));
  }
  return best;
};

// 拠点ごとのハザード露出。sites: [{name, lat, lng}] → [{name, hits: [{layer, name}]}]。
// 同じレイヤ項目に 2 拠点以上が乗っていれば「同時被災」の候補——本番と DR は別の行に置く。
export function geoExposure(sites, layers = null) {
  const hz = GEO_HAZARDS.filter((h) => !layers || layers.includes(h.layer));
  return sites.map((s) => {
    const p = [s.lat, s.lng];
    const hits = hz.filter((h) =>
      h.kind === 'zone' ? geoInPoly(p, h.pts)
        : h.kind === 'pt' ? geoKm(p, h.at) <= (h.km || 50)
          : geoLineKm(p, h.pts) <= (h.km || 30));
    return { name: s.name, hits: hits.map((h) => ({ layer: h.layer, name: h.name })) };
  });
}
